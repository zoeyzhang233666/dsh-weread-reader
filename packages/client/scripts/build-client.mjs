import { writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const PLUGIN = dirname(dirname(fileURLToPath(import.meta.url)))
const ROOT = dirname(dirname(PLUGIN))
const OUTPUT = join(PLUGIN, 'client.js')
const PLATFORM = ['react', 'react-dom', '@deepseek-ai/dsh-client-ui-primitives']

const require = createRequire(import.meta.url)
const esbuildCandidates = [
  join(ROOT, 'node_modules/esbuild/lib/main.js'),
  join(PLUGIN, 'node_modules/esbuild/lib/main.js'),
]

let build
for (const candidate of esbuildCandidates) {
  try {
    ;({ build } = require(candidate))
    break
  } catch {
    // try next
  }
}
if (!build) {
  throw new Error('esbuild not found. Place esbuild in repo node_modules.')
}

const result = await build({
  absWorkingDir: PLUGIN,
  entryPoints: ['src/index.js'],
  bundle: true,
  format: 'cjs',
  platform: 'browser',
  target: 'es2022',
  external: PLATFORM,
  charset: 'utf8',
  write: false,
  logLevel: 'silent',
  jsx: 'automatic',
  loader: { '.js': 'jsx' },
})

if (result.warnings.length) {
  throw new Error(result.warnings.map(warning => warning.text).join('\n'))
}

const text = [
  '// Generated by scripts/build-client.mjs. Do not edit by hand.',
  'window.__ModuleLoader__.load({',
  "  id: 'dsh-weread-reader',",
  '  factory: (require) => {',
  'const module = { exports: {} }',
  result.outputFiles[0].text.trimEnd(),
  "return Object.defineProperty({ ...module.exports }, Symbol.toStringTag, { value: 'Module' })",
  '  },',
  '})',
  '',
].join('\n')

writeFileSync(OUTPUT, text)
console.log(`wrote ${OUTPUT}`)
